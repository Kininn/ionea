# w3: game features (see w3-game-features.txt). A fresh data folder, two tiny GBA programs on the mGBA core (a
# cartridge header and a loop, no game), a stand-in for a native port (a copy of where.exe named as the
# Bloodborne port's program: it is only added, never run), windowed, muted, off screen, no real input.
# Usage: w3-game-features.ps1 [-Exe <Launcher.exe>] [-Root <dir>] [-Cores <folder with mgba_libretro.dll>, else IONEA_TEST_MGBA_CORE's folder]   (wipes <dir>)
param([string]$Exe = "$PSScriptRoot\..\bin\Release\net10.0-windows\Launcher.exe", [string]$Root = "$env:TEMP\Ionea-tests\w3",
      [string]$Cores = $(if ($env:IONEA_TEST_MGBA_CORE) { Split-Path $env:IONEA_TEST_MGBA_CORE }))
$ErrorActionPreference = 'Stop'
if (-not $Cores -or -not (Test-Path "$Cores\mgba_libretro.dll")) { "Give -Cores <folder with mgba_libretro.dll> (or IONEA_TEST_MGBA_CORE)"; exit 1 }
if (Test-Path $Root) { Remove-Item $Root -Recurse -Force }
$data = "$Root\data"; $shots = "$Root\shots"
New-Item -ItemType Directory -Force "$Root\roms", $data, $shots, "$Root\emu\Cores", "$Root\port\bbport" | Out-Null
Copy-Item "$env:WINDIR\System32\where.exe" "$Root\port\bbport\bbport-run.exe"
Copy-Item "$Cores\mgba_libretro.dll" "$Root\emu\Cores\"   # a copy: the test never touches the real one
# A GBA cartridge header (its logo and checksum) and an endless loop: enough for the core to run.
function New-Rom([string]$name, [string]$title) {
  $rom = New-Object byte[] 512
  [byte[]]$logo = 0x24,0xFF,0xAE,0x51,0x69,0x9A,0xA2,0x21,0x3D,0x84,0x82,0x0A,0x84,0xE4,0x09,0xAD,0x11,0x24,0x8B,0x98,0xC0,0x81,0x7F,0x21,0xA3,0x52,0xBE,0x19,0x93,0x09,0xCE,0x20,0x10,0x46,0x4A,0x4A,0xF8,0x27,0x31,0xEC,0x58,0xC7,0xE8,0x33,0x82,0xE3,0xCE,0xBF,0x85,0xF4,0xDF,0x94,0xCE,0x4B,0x09,0xC1,0x94,0x56,0x8A,0xC0,0x13,0x72,0xA7,0xFC,0x9F,0x84,0x4D,0x73,0xA3,0xCA,0x9A,0x61,0x58,0x97,0xA3,0x27,0xFC,0x03,0x98,0x76,0x23,0x1D,0xC7,0x61,0x03,0x04,0xAE,0x56,0xBF,0x38,0x84,0x00,0x40,0xA7,0x0E,0xFD,0xFF,0x52,0xFE,0x03,0x6F,0x95,0x30,0xF1,0x97,0xFB,0xC0,0x85,0x60,0xD6,0x80,0x25,0xA9,0x63,0xBE,0x03,0x01,0x4E,0x38,0xE2,0xF9,0xA2,0x34,0xFF,0xBB,0x3E,0x03,0x44,0x78,0x00,0x90,0xCB,0x88,0x11,0x3A,0x94,0x65,0xC0,0x7C,0x63,0x87,0xF0,0x3C,0xAF,0xD6,0x25,0xE4,0x8B,0x38,0x0A,0xAC,0x72,0x21,0xD4,0xF8,0x07
  [Array]::Copy($logo, 0, $rom, 4, $logo.Length)
  [byte[]]$b = 0x2E,0x00,0x00,0xEA; [Array]::Copy($b, 0, $rom, 0, 4)          # b 0xC0 (past the header)
  [byte[]]$loop = 0xFE,0xFF,0xFF,0xEA; [Array]::Copy($loop, 0, $rom, 0xC0, 4)  # b . (forever)
  $t = [Text.Encoding]::ASCII.GetBytes($title); [Array]::Copy($t, 0, $rom, 0xA0, $t.Length)
  $rom[0xB2] = 0x96
  $c = 0; for ($i = 0xA0; $i -le 0xBC; $i++) { $c = ($c - $rom[$i]) -band 0xFF }; $rom[0xBD] = ($c - 0x19) -band 0xFF
  [IO.File]::WriteAllBytes("$Root\roms\$name.gba", $rom)
}
New-Rom "Game One" "GAMEONE     "
New-Rom "Game Two" "GAMETWO     "
$env:IONEA_TESTROOT = $Root
$p = Start-Process -FilePath $Exe -WorkingDirectory "$PSScriptRoot\.." -PassThru -Wait -ArgumentList @(
  "--data", "`"$data`"", "--no-import", "--script", "`"$PSScriptRoot\w3-game-features.txt`"", "--shots", "`"$shots`"",
  "--emulators", "`"$Root\emu`"", "--windowed", "--mute", "--size", "1040x620", "--pos", "-30000,-30000")
$log = "$data\launcher.log"
"exit " + $p.ExitCode
if (Test-Path $log) { Select-String -Path $log -Pattern "FAIL|SCRIPT done|switch|home menu: (switching|.*closed after)|cover colour|emulators" | ForEach-Object { $_.Line } } else { "no log" }
